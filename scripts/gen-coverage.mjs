// Regenerates docs/wcag-coverage.md from src/rules/manifest.js — the single
// source of truth for rule coverage. Rows appear in manifest order, grouped
// by detection layer. Never hand-edit the doc; change the manifest (or this
// template) and regenerate.
//
//   node scripts/gen-coverage.mjs          # rewrite docs/wcag-coverage.md
//   node scripts/gen-coverage.mjs --check  # exit 1 if the doc is stale
//
// test/wcag-coverage-doc.test.mjs asserts the committed file equals
// generateDoc(), so a manifest edit without regeneration fails tests.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { RULES } from '../src/rules/manifest.js';

const DOC_PATH = new URL('../docs/wcag-coverage.md', import.meta.url);

const LAYERS = [
  ['static', 'Static layer'],
  ['rendered', 'Rendered layer'],
  ['crosspage', 'Cross-page layer'],
];

const cell = (s) => s.replaceAll('|', '\\|');
const plural = (n, one, many) => (n === 1 ? one : many);

export function generateDoc() {
  const wcag = RULES.filter((r) => r.level !== 'BP');
  const bp = RULES.filter((r) => r.level === 'BP');

  const out = [
    '# WCAG Coverage Reference',
    '',
    `${wcag.length} WCAG success criteria + ${bp.length} best-practice ${plural(bp.length, 'check', 'checks')} implemented across three`,
    'detection layers. This document',
    'is the authoritative map: each rule, its WCAG level/version, the detection',
    'layer that evaluates it, and what it flags. Live source: `GET /rules`.',
    '',
    'Layers: **static** = string-scan of fetched HTML (every scan), **rendered** =',
    'Browser Rendering trace (contrast census, focus cycle, target measurements),',
    '**crosspage** = multi-page consistency (site scans only).',
    '',
  ];

  for (const [how, title] of LAYERS) {
    const rows = wcag.filter((r) => r.how === how);
    out.push(`## ${title} (${rows.length} ${plural(rows.length, 'criterion', 'criteria')})`, '');
    out.push('| Criterion | Level | WCAG | What it flags |', '|---|---|---|---|');
    for (const r of rows) out.push(`| ${r.rule} — ${cell(r.name)} | ${r.level} | ${r.wcag} | ${cell(r.detects)} |`);
    out.push('');
  }

  out.push('## Best-practice checks (not numbered criteria)', '');
  out.push(
    'Checks for real problems no published criterion covers. `level: BP`, no',
    'conformance claim — filterable via `?level=BP` on reports.',
    '',
    '| Check | What it flags |',
    '|---|---|',
  );
  for (const r of bp) {
    const name = r.name.replace(/ \(best practice\)$/, '');
    out.push(`| ${r.rule} — ${cell(name)} | ${cell(r.detects)} |`);
  }
  out.push('');

  out.push(
    '---',
    '',
    '> Status note for agents/docs: `GET /rules` (backed by `src/rules/manifest.js`,',
    '> with `test/rules-manifest.test.mjs` enforcing that every emitted rule ID is',
    '> declared and vice versa) is the authoritative shipped list. Do not generate',
    '> tasks or docs claiming coverage beyond this manifest; do not propose',
    '> implementation work for criteria already listed here.',
    '>',
    '> This file is generated by `scripts/gen-coverage.mjs` (`npm run gen:coverage`)',
    '> and kept honest by `test/wcag-coverage-doc.test.mjs` — after editing',
    '> `src/rules/manifest.js`, regenerate instead of hand-editing.',
    '',
  );

  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const current = readFileSync(DOC_PATH, 'utf8');
  const generated = generateDoc();
  if (process.argv.includes('--check')) {
    if (generated !== current) {
      console.error('docs/wcag-coverage.md is stale — run `node scripts/gen-coverage.mjs`');
      process.exit(1);
    }
    console.log('docs/wcag-coverage.md is up to date');
  } else if (generated !== current) {
    writeFileSync(DOC_PATH, generated);
    console.log('docs/wcag-coverage.md regenerated');
  } else {
    console.log('docs/wcag-coverage.md already current');
  }
}
